    document.add_heading("3. Real Crawl Evidence", level=1)
    metrics = [
        ("Pages discovered", _audit_value(audit, "pages_discovered", default=0)),
        ("Pages crawled", _audit_value(audit, "pages_crawled", default=0)),
        ("Pages successful", _audit_value(audit, "pages_successful", default=0)),
        ("Pages failed", _audit_value(audit, "pages_failed", default=0)),
        ("Internal links", _audit_value(audit, "internal_links", default=0)),
        ("External links", _audit_value(audit, "external_links", default=0)),
        ("Broken internal links", _audit_value(audit, "broken_internal_links", default=0)),
        ("Orphan resources/pages", _audit_value(audit, "orphan_pages_count", default=0)),
        ("Sitemap found", "Yes" if _audit_value(audit, "sitemap_found", default=False) else "No"),
        ("Robots.txt found", "Yes" if _audit_value(audit, "robots_found", default=False) else "No"),
        ("Schema detected", "Yes" if _audit_value(audit, "schema_found", default=False) else "No"),
    ]

    table = document.add_table(rows=1, cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    _set_cell_text(table.rows[0].cells[0], "Measured metric", bold=True, color="FFFFFF")
    _set_cell_text(table.rows[0].cells[1], "Value", bold=True, color="FFFFFF")
    _shade_cell(table.rows[0].cells[0], TEAL)
    _shade_cell(table.rows[0].cells[1], TEAL)

    for label, value in metrics:
        cells = table.add_row().cells
        _set_cell_text(cells[0], label)
        _set_cell_text(cells[1], value, bold=True, color=NAVY)
        _shade_cell(cells[1], LIGHT)
        _add_bottom_border(cells[0])
        _add_bottom_border(cells[1])

    # Findings
    document.add_page_break()
    document.add_heading("4. Findings by SEO Skill", level=1)

    if not findings:
        document.add_paragraph(
            "No structured findings were available in the stored report content."
        )
    else:
        for index, finding in enumerate(findings, 1):
            severity = finding.severity.upper()
            severity_color = {
                "CRITICAL": CRITICAL,
                "HIGH": HIGH,
                "MEDIUM": MEDIUM,
                "LOW": LOW,
            }.get(severity, MUTED)

            card = document.add_table(rows=1, cols=1)
            cell = card.cell(0, 0)
            _shade_cell(cell, "F8FAFC")
            _set_cell_margins(cell, 110, 130, 110, 130)

            paragraph = cell.paragraphs[0]
            run = paragraph.add_run(f"{index:02d}  {severity}  ")
            run.bold = True
            run.font.size = Pt(8.5)
            run.font.color.rgb = RGBColor.from_string(severity_color)

            run = paragraph.add_run(finding.title)
            run.bold = True
            run.font.size = Pt(9.5)
            run.font.color.rgb = RGBColor.from_string(NAVY)

            if finding.url:
                paragraph = cell.add_paragraph()
                run = paragraph.add_run("Affected URL: ")
                run.bold = True
                run.font.size = Pt(8)
                run.font.color.rgb = RGBColor.from_string(BLUE)
                run = paragraph.add_run(finding.url)
                run.font.size = Pt(8)
                run.font.color.rgb = RGBColor.from_string(TEXT)

            for label, value in (
                ("What the crawl reports", finding.detail),
                ("Recommended action", finding.recommendation),
                ("Evidence", finding.evidence),
            ):
                if not value:
                    continue
                paragraph = cell.add_paragraph()
                run = paragraph.add_run(f"{label}: ")
                run.bold = True
                run.font.size = Pt(8)
                run.font.color.rgb = RGBColor.from_string(BLUE)
                run = paragraph.add_run(value)
                run.font.size = Pt(8)
                run.font.color.rgb = RGBColor.from_string(TEXT)

            document.add_paragraph().paragraph_format.space_after = Pt(1)

    # Page-level URL inventory
    document.add_page_break()
    document.add_heading("5. Page-Level URL Evidence", level=1)
    urls = _extract_urls(content)

    for finding in findings:
        if finding.url and finding.url not in urls:
            urls.append(finding.url)

    if urls:
        document.add_paragraph(
            "The URLs below are extracted from the stored audit report. "
            "No URL is invented by the export layer."
        )
        table = document.add_table(rows=1, cols=3)
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        for index, heading in enumerate(("No.", "Page URL", "Related finding")):
            _set_cell_text(
                table.rows[0].cells[index],
                heading,
                bold=True,
                color="FFFFFF",
                size=8,
            )
            _shade_cell(table.rows[0].cells[index], BLUE)

        for index, url in enumerate(urls, 1):
            related = next(
                (
                    finding.title
                    for finding in findings
                    if finding.url == url
                ),
                "URL referenced by audit evidence",
            )
            cells = table.add_row().cells
            _set_cell_text(cells[0], index, bold=True, color=NAVY, size=7)
            _set_cell_text(cells[1], url, size=7)
            _set_cell_text(cells[2], related, size=7)
            for cell in cells:
                _set_cell_margins(cell, 70, 70, 70, 70)
                _add_bottom_border(cell)
    else:
        document.add_paragraph(
            "No explicit page URLs were available in the stored report content."
        )

    # Data integrity
    document.add_heading("6. Data Integrity", level=1)
    integrity = [
        ("Crawler verified", "HTTP status, titles, meta descriptions, headings, canonicals, robots, schema, links and crawl metrics when present in the stored evidence."),
        ("Derived metrics", "Duplicate/missing counts and other metrics calculated from crawler evidence."),
        ("AI analysis", "Priorities, impact interpretation and recommendations produced by the SEO skills."),
        ("External data required", "Google rankings, Search Console performance, backlink authority/referring domains and competitor rankings require their respective integrations."),
    ]
    table = document.add_table(rows=1, cols=2)
    for j, heading in enumerate(("Evidence class", "Meaning")):
        _set_cell_text(table.rows[0].cells[j], heading, bold=True, color="FFFFFF")
        _shade_cell(table.rows[0].cells[j], BLUE)
    for label, value in integrity:
        cells = table.add_row().cells
        _set_cell_text(cells[0], label, bold=True, color=NAVY)
        _set_cell_text(cells[1], value)
        _shade_cell(cells[0], LIGHT)
        _add_bottom_border(cells[0])
        _add_bottom_border(cells[1])

    document.add_heading("7. Recommended Action Plan", level=1)
    actions = [
        "P0 — Resolve critical technical and indexability findings first.",
        "P0 — Fix duplicate titles, missing metadata, H1 problems and broken internal links identified by the crawl.",
        "P1 — Improve internal architecture and reduce excessive crawl depth.",
        "P1 — Verify local entity, Contact/About, schema and trust signals.",
        "P1 — Add or correct Article/BlogPosting/FAQPage/Person markup where the content supports it.",
        "P2 — Connect Search Console and backlink/competitor providers before reporting external ranking metrics.",
    ]
    for action in actions:
        document.add_paragraph(action, style="List Number")

    paragraph = document.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = paragraph.add_run(
        "BOOST RANKERS AI SEO OS  •  Professional evidence-based reporting"
    )
    run.bold = True
    run.font.size = Pt(8)
    run.font.color.rgb = RGBColor.from_string(MUTED)

    output = io.BytesIO()
    document.save(output)
    output.seek(0)

    filename = _safe_filename(
        getattr(report, "title", "seo-audit-report"),
        "docx",
    )
    return output.getvalue(), filename


