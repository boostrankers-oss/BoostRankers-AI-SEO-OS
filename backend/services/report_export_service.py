@dataclass
class Finding:
    severity: str
    title: str
    detail: str = ""
    recommendation: str = ""
    evidence: str = ""
    url: str = ""


def _clean(value: Any) -> str:
    if value is None:
        return ""
    value = unescape(str(value))
    value = re.sub(r"\s+", " ", value)
    return value.strip()


def _audit_value(audit: Any, *names: str, default: Any = 0) -> Any:
    for name in names:
        try:
            value = getattr(audit, name, None)
        except Exception:
            value = None
        if value is not None:
            return value
    return default


def _format_score(value: Any) -> str:
    try:
        return f"{float(value):.1f}/100"
    except Exception:
        return "N/A"


def _extract_website(report: Any) -> str:
    audit = getattr(report, "audit", None)
    website = _audit_value(audit, "website", "url", default="")
    if website:
        return _clean(website)

    match = re.search(r"https?://[^\s|)>]+", _clean(getattr(report, "content", "")))
    return match.group(0).rstrip(".,") if match else ""


def _parse_scorecard(content: str) -> dict[str, str]:
    result: dict[str, str] = {}
    areas = (
        "Technical SEO",
        "Content SEO",
        "Local SEO",
        "Schema",
        "EEAT",
        "Internal Linking",
        "Competitor",
        "Backlink",
        "AI Search",
    )
    for area in areas:
        match = re.search(
            rf"{re.escape(area)}(?:\s+SEO)?\s*\|\s*([0-9]+(?:\.[0-9]+)?/100)",
            content,
            re.I,
        )
        if match:
            result[area] = match.group(1)
            continue
        match = re.search(
            rf"{re.escape(area)}(?:\s+SEO)?[^\n]{{0,80}}?([0-9]+(?:\.[0-9]+)?/100)",
            content,
            re.I,
        )
        if match:
            result[area] = match.group(1)
    return result


def _parse_dict_findings(content: str) -> list[Finding]:
    """
    Converts legacy Python-dict/JSON-like finding text into structured findings.
    This prevents raw {'severity': ...} output in exports.
    """
    findings: list[Finding] = []

    pattern = re.compile(
        r"\{['\"]severity['\"]\s*:\s*['\"](?P<severity>[^'\"]+)['\"]"
        r".*?['\"]title['\"]\s*:\s*['\"](?P<title>.*?)['\"]"
        r".*?['\"]detail['\"]\s*:\s*['\"](?P<detail>.*?)['\"]"
        r".*?['\"]recommendation['\"]\s*:\s*['\"](?P<recommendation>.*?)['\"]"
        r".*?['\"]evidence['\"]\s*:\s*['\"](?P<evidence>.*?)['\"]\s*\}",
        re.I | re.S,
    )

    for match in pattern.finditer(content):
        data = match.groupdict()
        findings.append(
            Finding(
                severity=_clean(data["severity"]).lower(),
                title=_clean(data["title"]),
                detail=_clean(data["detail"]),
                recommendation=_clean(data["recommendation"]),
                evidence=_clean(data["evidence"]),
            )
        )
    return findings


def _parse_markdown_findings(content: str) -> list[Finding]:
    """
    Parses the normal report markdown generated by the audit service.
    It recognizes severity-led lines and subsequent evidence/recommendation text.
    """
    findings: list[Finding] = []
    lines = content.splitlines()
    current: Finding | None = None

    severity_re = re.compile(
        r"^\s*(?:[-*]\s*)?(CRITICAL|HIGH|MEDIUM|LOW)\s*(?:—|-|:)\s*(.+)$",
        re.I,
    )

    for raw in lines:
        line = _clean(raw)
        if not line:
            continue

        match = severity_re.match(line)
        if match:
            if current:
                findings.append(current)
            current = Finding(
                severity=match.group(1).lower(),
                title=_clean(match.group(2)),
            )
            urls = re.findall(r"https?://[^\s<>'\")]+", current.title)
            if urls:
                current.url = urls[0].rstrip(".,")
            continue

        if current is None:
            continue

        lower = line.lower()
        if lower.startswith("evidence:"):
            current.evidence = _clean(line.split(":", 1)[1])
        elif lower.startswith("recommended action:"):
            current.recommendation = _clean(line.split(":", 1)[1])
        elif lower.startswith("recommendation:"):
            current.recommendation = _clean(line.split(":", 1)[1])
        elif lower.startswith("what the crawl reports:"):
            current.detail = _clean(line.split(":", 1)[1])
        elif current.detail == "" and not line.startswith("#"):
            current.detail = line

    if current:
        findings.append(current)

    return findings


def extract_findings(content: str) -> list[Finding]:
    findings = _parse_dict_findings(content)
    if findings:
        return findings

    return _parse_markdown_findings(content)


def _extract_urls(content: str) -> list[str]:
    urls = re.findall(r"https?://[^\s<>'\")\],]+", content)
    output: list[str] = []
    seen: set[str] = set()
    for url in urls:
        url = url.rstrip(".,;:")
        if url not in seen:
            seen.add(url)
            output.append(url)
    return output


def _issue_counts(findings: list[Finding]) -> dict[str, int]:
    counts = {"critical": 0, "high": 0, "medium": 0, "low": 0}
    for finding in findings:
        severity = finding.severity.lower()
        if severity in counts:
            counts[severity] += 1
    return counts


def _safe_filename(value: str, extension: str) -> str:
    value = re.sub(r"[\\/:*?\"<>|]+", "-", value).strip(" .")
    value = value or "seo-audit-report"
    return f"{value}.{extension}"


